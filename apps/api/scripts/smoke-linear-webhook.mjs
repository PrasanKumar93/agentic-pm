#!/usr/bin/env node
import { createHmac, randomUUID } from "node:crypto";
import { existsSync, readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(scriptDir, "../../..");

loadEnvFile(resolve(repoRoot, ".env"));

const args = process.argv.slice(2);
const help = hasFlag(args, "--help") || hasFlag(args, "-h");
const dryRun = hasFlag(args, "--dry-run");
const json = hasFlag(args, "--json");
const skipReplay = hasFlag(args, "--no-replay");
const allowMissingWorkItem = hasFlag(args, "--allow-missing-work-item");

if (help) {
  printHelp();
  process.exit(0);
}

const apiUrl = trimTrailingSlash(
  readArg(args, "--api-url") ??
    process.env.AGENTIC_PM_API_URL ??
    `http://127.0.0.1:${process.env.API_PORT ?? "4000"}`,
);
const endpointUrl = `${apiUrl}/webhooks/linear`;
const timestamp = Date.now();
const shortId = randomUUID().slice(0, 8);
const identifier = readArg(args, "--identifier") ?? `SMK-${timestamp}`;
const issueExternalId =
  readArg(args, "--issue-id") ?? `issue_linear_webhook_smoke_${timestamp}_${shortId}`;
const deliveryId =
  readArg(args, "--delivery-id") ?? `local-linear-smoke-${timestamp}-${shortId}`;
const state = readArg(args, "--state") ?? process.env.LINEAR_WEBHOOK_SMOKE_STATE ?? "Todo";
const action = readArg(args, "--action") ?? "update";
const title = readArg(args, "--title") ?? `Linear webhook smoke ${identifier}`;
const secret = process.env.LINEAR_WEBHOOK_SECRET?.trim();

const payload = {
  type: "Issue",
  action,
  webhookId: `webhook_${shortId}`,
  webhookTimestamp: timestamp,
  url: `https://linear.app/agentic-pm/issue/${identifier.toLowerCase()}`,
  data: {
    id: issueExternalId,
    identifier,
    title,
    description:
      "Local signed webhook smoke generated by Agentic PM. Safe to delete after validation.",
    url: `https://linear.app/agentic-pm/issue/${identifier.toLowerCase()}`,
    state: {
      name: state,
    },
    labels: {
      nodes: [{ name: "agent" }, { name: "webhook-smoke" }],
    },
    createdAt: new Date(timestamp).toISOString(),
    updatedAt: new Date(timestamp).toISOString(),
  },
};
const body = JSON.stringify(payload);
const signature = secret ? signBody(body, secret) : undefined;

if (dryRun) {
  printDryRun({
    endpointUrl,
    deliveryId,
    identifier,
    issueExternalId,
    payload,
    secretConfigured: Boolean(secret),
    signature,
  });
  process.exit(0);
}

if (!secret) {
  fail(
    "LINEAR_WEBHOOK_SECRET is missing. Add it to .env and restart the API with the same value before running this smoke.",
  );
}

const headers = {
  "Content-Type": "application/json",
  "Linear-Signature": signature,
  "Linear-Event": "Issue",
  "Linear-Delivery": deliveryId,
};

const first = await requestJson(endpointUrl, {
  method: "POST",
  headers,
  body,
});

if (!first.ok) {
  fail(`Linear webhook smoke failed on first POST (${first.status}).`, {
    response: first.body ?? first.text,
  });
}

const firstData = first.body?.data;
if (firstData?.status !== "reconciled") {
  fail("Linear webhook smoke did not reconcile the issue payload.", {
    response: first.body,
  });
}

if (!firstData.workItemId && !allowMissingWorkItem) {
  fail(
    "Linear webhook smoke reconciled the issue but did not create a work item. Use --allow-missing-work-item when intentionally testing an inactive Linear state.",
    { response: first.body },
  );
}

let replay;
if (!skipReplay) {
  replay = await requestJson(endpointUrl, {
    method: "POST",
    headers,
    body,
  });

  if (!replay.ok || replay.body?.data?.status !== "duplicate") {
    fail("Linear webhook replay did not return the expected duplicate result.", {
      response: replay.body ?? replay.text,
      status: replay.status,
    });
  }
}

const deliveries = await requestJson(`${apiUrl}/webhook-deliveries?limit=50`);
if (!deliveries.ok) {
  fail(`Could not read webhook delivery ledger (${deliveries.status}).`, {
    response: deliveries.body ?? deliveries.text,
  });
}
const delivery = deliveries.body?.data?.find(
  (item) => item.deliveryId === deliveryId,
);

if (!delivery) {
  fail("Webhook delivery was accepted but not found in the delivery ledger.", {
    deliveryId,
    response: deliveries.body,
  });
}

let workItem;
if (firstData.workItemId) {
  const workItems = await requestJson(`${apiUrl}/work-items?limit=100`);
  if (!workItems.ok) {
    fail(`Could not read work items (${workItems.status}).`, {
      response: workItems.body ?? workItems.text,
    });
  }
  workItem = workItems.body?.data?.find((item) => item.id === firstData.workItemId);

  if (!workItem) {
    fail("Webhook work item was returned by the API but not found in /work-items.", {
      workItemId: firstData.workItemId,
      response: workItems.body,
    });
  }
}

printSuccess({
  endpointUrl,
  delivery,
  deliveryId,
  first,
  identifier,
  issueExternalId,
  replay,
  state,
  workItem,
});

function printDryRun(summary) {
  if (json) {
    console.log(JSON.stringify({ mode: "dry-run", ...summary }, null, 2));
    return;
  }

  console.log("Agentic PM Linear webhook smoke (dry-run)");
  console.log(`Endpoint: ${summary.endpointUrl}`);
  console.log(`Issue: ${summary.identifier} (${summary.issueExternalId})`);
  console.log(`Delivery: ${summary.deliveryId}`);
  console.log(
    `Signature: ${
      summary.signature ? `${summary.signature.slice(0, 12)}...` : "requires LINEAR_WEBHOOK_SECRET"
    }`,
  );
  console.log("");
  console.log(JSON.stringify(summary.payload, null, 2));
}

function printSuccess(summary) {
  const output = {
    ok: true,
    endpointUrl: summary.endpointUrl,
    issue: {
      identifier: summary.identifier,
      externalId: summary.issueExternalId,
      state: summary.state,
    },
    firstPost: {
      httpStatus: summary.first.status,
      status: summary.first.body?.data?.status,
      active: summary.first.body?.data?.active,
      issueId: summary.first.body?.data?.issueId,
      workItemId: summary.first.body?.data?.workItemId,
    },
    replay: summary.replay
      ? {
          httpStatus: summary.replay.status,
          status: summary.replay.body?.data?.status,
        }
      : undefined,
    delivery: pickDelivery(summary.delivery),
    workItem: summary.workItem ? pickWorkItem(summary.workItem) : undefined,
  };

  if (json) {
    console.log(JSON.stringify(output, null, 2));
    return;
  }

  console.log("Agentic PM Linear webhook smoke passed");
  console.log(`Endpoint: ${output.endpointUrl}`);
  console.log(`Issue: ${output.issue.identifier} (${output.issue.state})`);
  console.log(`First POST: ${output.firstPost.status}`);
  console.log(
    `Replay: ${output.replay ? output.replay.status : "skipped with --no-replay"}`,
  );
  console.log(
    `Delivery ledger: ${output.delivery.status}, attempts ${output.delivery.attemptCount}`,
  );
  console.log(
    `Work item: ${output.workItem ? `${output.workItem.id} (${output.workItem.status})` : "not created"}`,
  );
}

function pickDelivery(delivery) {
  return {
    deliveryId: delivery.deliveryId,
    event: delivery.event,
    action: delivery.action,
    type: delivery.type,
    status: delivery.status,
    attemptCount: delivery.attemptCount,
    projectId: delivery.projectId,
    result: delivery.result,
  };
}

function pickWorkItem(workItem) {
  return {
    id: workItem.id,
    issueId: workItem.issueId,
    issueIdentifier: workItem.issueIdentifier,
    title: workItem.title,
    status: workItem.status,
    projectId: workItem.projectId,
    repositoryId: workItem.repositoryId,
  };
}

async function requestJson(url, options = {}) {
  const response = await fetch(url, options);
  const text = await response.text();
  let body;
  try {
    body = text ? JSON.parse(text) : undefined;
  } catch {
    body = undefined;
  }

  return {
    ok: response.ok,
    status: response.status,
    body,
    text,
  };
}

function signBody(value, secretValue) {
  return createHmac("sha256", secretValue).update(value).digest("hex");
}

function fail(message, details) {
  if (json) {
    console.error(JSON.stringify({ ok: false, error: message, details }, null, 2));
  } else {
    console.error(message);
    if (details) {
      console.error(JSON.stringify(details, null, 2));
    }
  }
  process.exit(1);
}

function printHelp() {
  console.log(`Usage: pnpm smoke:linear-webhook [-- options]

Posts a signed Linear Issue webhook to the local Agentic PM API and verifies
that the issue is reconciled, delivery replay is deduplicated, and the delivery
ledger/work board can read back the result.

Required for live mode:
  LINEAR_WEBHOOK_SECRET must be present in .env and the API must be running with
  the same value.

Options:
  --api-url <url>              API base URL. Defaults to http://127.0.0.1:$API_PORT or :4000.
  --identifier <key>           Linear issue identifier. Defaults to SMK-<timestamp>.
  --issue-id <id>              Linear external issue id. Defaults to a unique smoke id.
  --delivery-id <id>           Linear-Delivery header. Defaults to a unique smoke id.
  --state <name>               Linear workflow state. Defaults to LINEAR_WEBHOOK_SMOKE_STATE or Todo.
  --action <create|update>     Linear webhook action. Defaults to update.
  --title <text>               Linear issue title.
  --dry-run                    Print the payload and signature preview without posting.
  --no-replay                  Skip duplicate delivery replay verification.
  --allow-missing-work-item    Allow reconciled inactive states that do not create work.
  --json                       Print machine-readable output.
  --help                       Show this message.
`);
}

function hasFlag(values, name) {
  return values.includes(name);
}

function readArg(values, name) {
  for (let index = 0; index < values.length; index += 1) {
    const value = values[index];
    if (value === name && values[index + 1] && !values[index + 1].startsWith("--")) {
      return values[index + 1];
    }

    if (value.startsWith(`${name}=`)) {
      return value.slice(name.length + 1);
    }
  }

  return undefined;
}

function trimTrailingSlash(value) {
  return value.replace(/\/+$/u, "");
}

function loadEnvFile(path) {
  if (!existsSync(path)) {
    return;
  }

  const lines = readFileSync(path, "utf8").split(/\r?\n/u);
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) {
      continue;
    }

    const separator = trimmed.indexOf("=");
    if (separator === -1) {
      continue;
    }

    const key = trimmed.slice(0, separator).trim();
    const value = unquoteEnvValue(trimmed.slice(separator + 1).trim());
    if (key && process.env[key] === undefined) {
      process.env[key] = value;
    }
  }
}

function unquoteEnvValue(value) {
  if (
    (value.startsWith('"') && value.endsWith('"')) ||
    (value.startsWith("'") && value.endsWith("'"))
  ) {
    return value.slice(1, -1);
  }

  return value;
}
